#!/bin/sh
# Regenerates src/parts/headlight_shaders.h from src/shaders/*.asm (needs build/fxdump.exe: build.bat).
HERE="$(cd "$(dirname "$0")" && pwd)"
SRC="$HERE/../../src"
FX="$HERE/build/fxdump.exe"
OUT="$SRC/parts/headlight_shaders.h"
TMP="$OUT.tmp"
echo "// Generated by tools/fxdump/gen_shaders.sh from src/shaders/*.asm. Don't edit." > "$TMP"
"$FX" frag "$SRC/shaders/hl_vs_extra.asm" kHlVsExtra >> "$TMP" || { rm -f "$TMP"; exit 1; }
for s in world depth reflect depthreflect; do
    "$FX" asm "$SRC/shaders/hl_ps_$s.asm" "kHlPs_$s" >> "$TMP" || { rm -f "$TMP"; exit 1; }
done
sed 's#// .*/src/shaders/#// src/shaders/#' "$TMP" | tr -d '\r' > "$OUT" && rm -f "$TMP" && echo "wrote $OUT"
