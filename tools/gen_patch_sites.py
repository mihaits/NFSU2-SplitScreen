"""Writes src/parts/patch_sites.h: the game's original bytes at every WriteJump site of the plugin's source, read from
speed2.exe on disk (it must be the unpatched v1.2 exe). The plugin compares them with the running game before it
patches (VerifyPatchSites) and logs the sites another mod changed. Run after adding, moving or resizing a WriteJump:
python gen_patch_sites.py            (prints each site as it goes; exits 1 on a site it can't resolve)
"""
import glob, os, re, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paths import EXE

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src')
OUT = os.path.join(SRC, 'parts', 'patch_sites.h')
MAX_LEN = 32

files = [f for pat in ('*.cpp', '*.h', 'parts/*.cpp', 'parts/*.h') for f in glob.glob(os.path.join(SRC, pat))
         if os.path.abspath(f) != os.path.abspath(OUT)]
text = {f: open(f, encoding='utf-8', errors='replace').read() for f in files}
defines = {}
for t in text.values():
    for name, value in re.findall(r'^#define\s+(\w+)\s+(0x[0-9A-Fa-f]+)\b', t, re.M):
        defines[name] = int(value, 16)
arrays = {}     # name -> element count, for sizeof(name) lengths
for t in text.values():
    for name, body in re.findall(r'uint8_t\s+(\w+)\[\]\s*=\s*\{([^}]*)\}', t):
        arrays[name] = len([x for x in body.split(',') if x.strip()])

d = open(EXE, 'rb').read()
pe = struct.unpack_from('<I', d, 0x3C)[0]
nsec = struct.unpack_from('<H', d, pe + 6)[0]
opt = struct.unpack_from('<H', d, pe + 20)[0]
base = struct.unpack_from('<I', d, pe + 52)[0]
secs = [struct.unpack_from('<IIII', d, pe + 24 + opt + i * 40 + 8) for i in range(nsec)]   # vsize, va, rawsize, raw

def read(va, n):
    for vs, sva, rs, raw in secs:
        if base + sva <= va and va + n <= base + sva + rs:
            return d[raw + va - base - sva:raw + va - base - sva + n]
    return None

sites, bad = {}, []
for f, t in sorted(text.items()):
    for m in re.finditer(r'\bWriteJump\(\s*(\w+)\s*,[^,;]+,\s*([^;]+?)\)\s*;', t):
        where, length = m.group(1), m.group(2).strip()
        at = defines.get(where)
        size = re.fullmatch(r'sizeof\((\w+)\)', length)
        n = arrays.get(size.group(1)) if size else int(length) if length.isdigit() else None
        code = read(at, n) if at and n and n <= MAX_LEN else None
        if not code:
            bad.append(f'{os.path.basename(f)}: WriteJump({where}, .., {length})')
            continue
        if sites.get(at, (where, code))[1] != code: bad.append(f'{where}: two lengths')
        sites[at] = (where, code)
        print(f'{at:08X} {n:2d} {code.hex(" ")}  {where}', flush=True)
if bad:
    sys.exit('not resolved:\n  ' + '\n  '.join(bad))

lines = ['// Generated by tools/gen_patch_sites.py from speed2.exe v1.2: the game\'s bytes at every WriteJump site.',
         '// Not edited by hand; included by core.cpp.',
         f'struct PatchSite {{ uint32_t at; uint8_t len; uint8_t bytes[{MAX_LEN}]; }};',
         'static const PatchSite kPatchSites[] = {']
for at, (where, code) in sorted(sites.items()):
    lines.append(f'    {{0x{at:06X}, {len(code)}, {{{", ".join(f"0x{b:02X}" for b in code)}}}}},   // {where}')
lines.append('};')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(f'{len(sites)} sites -> {os.path.relpath(OUT)}')
